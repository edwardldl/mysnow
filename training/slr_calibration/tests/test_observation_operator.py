"""Tests for the step-4 observation operator (research track).

The centrepiece is a planted-parameter recovery test: a synthetic
hourly series is generated by running the operator itself with known
parameters, and the observation-space fit must recover them.  The
remaining tests pin the unit conversions, storm segmentation, mass
accounting, and the exact no-settlement arithmetic.
"""
from __future__ import annotations

import json
import math
import tempfile
import unittest
from datetime import date, datetime, timedelta
from pathlib import Path

from slr_calibration.observation_operator import (
    HourlySeries,
    OperatorParams,
    StormWindow,
    board_window_idx,
    fit_operator,
    invert_window,
    load_hourly_series,
    segment_storms,
    simulate_window,
    slr_metrics,
)


def _flat_series(hours: int = 96, swe: float = 500.0, depth: float = 1500.0,
                 temp: float = -4.0) -> HourlySeries:
    start = datetime(2024, 1, 1)
    return HourlySeries(
        triplet="TEST",
        times=[start + timedelta(hours=i) for i in range(hours)],
        swe_mm=[swe] * hours,
        depth_mm=[depth] * hours,
        temp_c=[temp] * hours,
    )


class LoadHourlySeriesTest(unittest.TestCase):
    def test_merges_and_converts(self) -> None:
        payload = [{
            "stationTriplet": "999:XX:SNTL",
            "data": [
                {"stationElement": {"elementCode": "WTEQ", "storedUnitCode": "in"},
                 "values": [{"date": "2025-01-01 00:00", "value": 10.0},
                            {"date": "2025-01-01 01:00", "value": 10.1}]},
                {"stationElement": {"elementCode": "SNWD", "storedUnitCode": "in"},
                 "values": [{"date": "2025-01-01 00:00", "value": 50},
                            {"date": "2025-01-01 01:00", "value": 51}]},
                {"stationElement": {"elementCode": "TOBS", "storedUnitCode": "degF"},
                 "values": [{"date": "2025-01-01 00:00", "value": 32.0},
                            {"date": "2025-01-01 01:00", "value": 23.0}]},
            ],
        }]
        with tempfile.TemporaryDirectory() as tmp:
            cache = Path(tmp)
            (cache / "999_XX_SNTL_202501.json").write_text(json.dumps(payload), encoding="utf-8")
            series = load_hourly_series(cache, "999:XX:SNTL")
        self.assertEqual(series.times[0], datetime(2025, 1, 1, 0, 0))
        self.assertAlmostEqual(series.swe_mm[0], 254.0)
        self.assertAlmostEqual(series.depth_mm[1], 51 * 25.4)
        self.assertAlmostEqual(series.temp_c[0], 0.0)
        self.assertAlmostEqual(series.temp_c[1], -5.0)


class SegmentationTest(unittest.TestCase):
    def test_finds_gain_window(self) -> None:
        series = _flat_series(hours=24 * 30)
        swe = list(series.swe_mm)
        for i in range(10 * 24, len(swe)):
            gained_hours = min(max(i - 10 * 24, 0), 20)
            swe[i] = 500.0 + 1.5 * gained_hours
        series.swe_mm = swe  # type: ignore[assignment]
        windows = segment_storms(series)
        self.assertEqual(len(windows), 1)
        self.assertGreaterEqual(windows[0].total_gain_mm, 25.0)


class SimulationTest(unittest.TestCase):
    def test_no_deposition_no_new_layer(self) -> None:
        series = _flat_series()
        params = OperatorParams(log_eta_new=30.0, log_eta_old=30.0)  # ~no compaction
        sim = simulate_window(series, list(range(25)), params)
        self.assertIsNotNone(sim)
        assert sim is not None
        self.assertEqual(sim.new_layer_depth_mm, 0.0)
        self.assertEqual(sim.gauge_swe_mm, 0.0)
        self.assertTrue(all(abs(d - 1500.0) < 1e-3 for d in sim.depth_sim_mm))

    def test_mass_and_depth_ratio_without_settlement(self) -> None:
        series = _flat_series()
        # Deposit 24 mm of pillow SWE evenly over 24 h.
        series.swe_mm = [500.0 + float(i) for i in range(25)] + [524.0] * 71  # type: ignore[assignment]
        # rho0 = RHO_META so the fixed metamorphism branch is inert and
        # the no-settlement arithmetic is exact.
        params = OperatorParams(gamma=1.2, rho0_intercept=200.0, rho0_temp_slope=0.0,
                                log_eta_new=30.0, log_eta_old=30.0)
        sim = simulate_window(series, list(range(25)), params)
        self.assertIsNotNone(sim)
        assert sim is not None
        self.assertAlmostEqual(sim.pillow_gain_mm, 24.0, places=9)
        self.assertAlmostEqual(sim.gauge_swe_mm, 20.0, places=9)          # 24 / gamma
        self.assertAlmostEqual(sim.new_layer_depth_mm, 100.0, places=4)   # 20 mm at 200 kg/m3
        inv = invert_window(series, list(range(25)), params)
        self.assertIsNotNone(inv["recoveredSlr"])
        self.assertAlmostEqual(inv["recoveredSlr"], 5.0, places=4)        # 1000 / rho0

    def test_old_pack_settlement_reduces_total_depth(self) -> None:
        series = _flat_series()
        series.swe_mm = [500.0 + float(i) for i in range(25)] + [524.0] * 71  # type: ignore[assignment]
        base = OperatorParams(gamma=1.0, rho0_intercept=100.0, rho0_temp_slope=0.0,
                              log_eta_new=30.0, log_eta_old=30.0)
        settling = OperatorParams(gamma=1.0, rho0_intercept=100.0, rho0_temp_slope=0.0,
                                  log_eta_new=30.0, log_eta_old=14.0)
        sim_base = simulate_window(series, list(range(25)), base)
        sim_settle = simulate_window(series, list(range(49)), settling)
        self.assertIsNotNone(sim_base)
        self.assertIsNotNone(sim_settle)
        assert sim_base is not None and sim_settle is not None
        # With old-pack settlement active, total depth at hour 48 is
        # lower than the no-settlement trajectory by a wide margin,
        # even though deposition is identical.
        self.assertLess(sim_settle.depth_sim_mm[-1], sim_base.depth_sim_mm[-1] - 50.0)


def _synthetic_fit_case() -> tuple[HourlySeries, list[StormWindow], OperatorParams]:
    truth = OperatorParams(gamma=1.25, rho0_intercept=95.0, rho0_temp_slope=2.5,
                           log_eta_new=17.2, log_eta_old=17.8)
    total_hours = 24 * 130
    start = datetime(2024, 1, 1)
    times = [start + timedelta(hours=i) for i in range(total_hours)]
    pillow = [0.0] * total_hours
    temp = [-4.0] * total_hours
    specs = [(5, 30.0, 18, -6.0), (25, 45.0, 30, -2.0), (45, 25.0, 15, -9.0),
             (65, 55.0, 36, -1.0), (88, 35.0, 22, -5.0), (108, 40.0, 26, -3.0)]
    windows: list[StormWindow] = []
    for start_day, total, span, temp_c in specs:
        first = start_day * 24
        shape = [math.sin(math.pi * (k + 0.5) / span) for k in range(span)]
        scale = total / sum(shape)
        for k in range(span):
            pillow[first + k] = shape[k] * scale
            temp[first + k] = temp_c
        windows.append(StormWindow(first - 12, first + span + 12, total))
    swe = [500.0]
    for i in range(1, total_hours):
        swe.append(swe[-1] + pillow[i])
    series = HourlySeries("SYNTH", times, swe, [None] * total_hours, temp)  # type: ignore[arg-type]
    depth: list[float | None] = [None] * total_hours
    depth[0] = 1600.0
    cursor_depth = 1600.0
    cursor = 0
    for window in windows:
        # Fill the gap before the window (and its initial state) with a
        # constant depth.
        for i in range(cursor, window.start_idx + 1):
            depth[i] = cursor_depth
        series.depth_mm = list(depth)  # type: ignore[arg-type]
        idx = list(range(window.start_idx, window.end_idx + 1))
        sim = simulate_window(series, idx, truth)
        assert sim is not None
        for pos, i in enumerate(idx):
            depth[i] = sim.depth_sim_mm[pos]
        cursor_depth = depth[window.end_idx] or cursor_depth
        cursor = window.end_idx + 1
    for i in range(cursor, total_hours):
        depth[i] = cursor_depth
    series.depth_mm = depth  # type: ignore[assignment]
    return series, windows, truth


class FitRecoveryTest(unittest.TestCase):
    def test_fit_recovers_planted_parameters(self) -> None:
        series, windows, truth = _synthetic_fit_case()
        fit = fit_operator(series, windows, starts=(OperatorParams(),))
        params = fit["params"]
        self.assertIsNotNone(fit["depthRmseMm"])
        self.assertLess(fit["depthRmseMm"], 2.0)
        self.assertLess(abs(params.gamma - truth.gamma), 0.12)
        self.assertLess(abs(params.rho0_intercept - truth.rho0_intercept), 25.0)


class PairingAndMetricsTest(unittest.TestCase):
    def test_board_window_idx_spans_24_steps(self) -> None:
        series = _flat_series(hours=24 * 10)
        idx = board_window_idx(series, date(2024, 1, 5), (-1, 0))
        self.assertIsNotNone(idx)
        assert idx is not None
        self.assertEqual(len(idx), 25)
        self.assertEqual(series.times[idx[-1]], datetime(2024, 1, 4, 0, 0))

    def test_slr_metrics(self) -> None:
        block = slr_metrics([(10.0, 12.0), (8.0, 8.0)])
        self.assertEqual(block["n"], 2)
        self.assertEqual(block["mae"], 1.0)
        self.assertEqual(block["bias"], -1.0)


